function cfg = profile_quadriga(kind, name, seed)
%PROFILE Return a compact, reproducible generator configuration.
%
% cfg = channelgen.profile("quadriga", "uma_nlos")
% cfg = channelgen.profile("block", "paper_demo")
% cfg = channelgen.profile("cs", "roth_gaussian")
if nargin < 3
    seed = 1729;
end

kind = lower(string(kind));
name = lower(string(name));

switch kind
    case "quadriga"
        cfg = quadrigaProfile(name, seed);
    case "block"
        cfg = blockProfile(name);
    case "cs"
        cfg = csProfile(name);
    otherwise
        error("channelgen:profile:UnknownKind", ...
            "Unknown profile kind '%s'.", kind);
end
end

function cfg = quadrigaProfile(name, seed)
cfg = struct( ...
    "scenario", "3GPP_38.901_UMa_NLOS", ...
    "centerFrequency", 12e9, ...
    "subcarrierSpacing", 30e3, ...
    "numSubcarriers", 256, ...
    "txSize", [4 4], ...
    "rxSize", [2 2], ...
    "txSpacing", [0.5 0.5], ...
    "rxSpacing", [0.5 0.5], ...
    "bsHeight", 25, ...
    "ueHeight", 1.5, ...
    "distance", [50 250], ...
    "numUsers", 1, ...
    "seed", seed, ...
    "outputShape", "flat", ...
    "tuningFraction", 0.2, ...
    "delayEnergyFraction", 0.998, ...
    "showProgress", false, ...
    "quadrigaRoot", "");

switch name
    case "uma_nlos"
        % Defaults above.
    case "paper_ula"
        cfg.numSubcarriers = 1596;
        cfg.txSize = [64 1];
        cfg.rxSize = [4 1];
        cfg.numUsers = 1;
        cfg.tuningFraction = 1/3;
    case "umi_nlos"
        cfg.scenario = "3GPP_38.901_UMi_NLOS";
        cfg.centerFrequency = 28e9;
        cfg.txSize = [8 8];
        cfg.distance = [10 100];
        cfg.bsHeight = 10;
    case "legacy_12ghz"
        cfg.scenario = "3GPP_38.901_UMa_NLOS";
        cfg.centerFrequency = 12e9;
        cfg.subcarrierSpacing = 15e3;
        cfg.numSubcarriers = 1024;
        cfg.txSize = [4 4];
        cfg.rxSize = [1 1];
        cfg.distance = 150;
        cfg.numUsers = 5;
    case "smoke_test"
        cfg.numSubcarriers = 8;
        cfg.txSize = [1 1];
        cfg.rxSize = [1 1];
        cfg.distance = 100;
        cfg.numUsers = 2;
        cfg.tuningFraction = 0.5;
    case "algorithm_smoke"
        cfg.numSubcarriers = 256;
        cfg.txSize = [16 1];
        cfg.rxSize = [4 1];
        cfg.numUsers = 3;
        cfg.tuningFraction = 1/3;
    otherwise
        error("channelgen:profile:UnknownProfile", ...
            "Unknown QuaDRiGa profile '%s'.", name);
end
end

function cfg = blockProfile(name)
switch name
    case "paper_demo"
        cfg = struct( ...
            "dimensions", [8 16 2304], ...
            "s", 8, ...
            "sigma", 32, ...
            "numSamples", 5, ...
            "seed", seed, ...
            "normalize", true);
    case "smoke_test"
        cfg = struct( ...
            "dimensions", [2 3 16], ...
            "s", 2, ...
            "sigma", 2, ...
            "numSamples", 2, ...
            "seed", seed, ...
            "normalize", true);
    otherwise
        error("channelgen:profile:UnknownProfile", ...
            "Unknown block-channel profile '%s'.", name);
end
end

function cfg = csProfile(name)
switch name
    case "roth_gaussian"
        cfg = struct( ...
            "ensemble", "gaussian", ...
            "N", 30, "n", 100, "s", 4, "sigma", 20, ...
            "m", 300, "field", "real", "snrDb", Inf, ...
            "seed", seed);
    case "roth_gaussian_noisy"
        cfg = struct( ...
            "ensemble", "gaussian", ...
            "N", 30, "n", 100, "s", 4, "sigma", 20, ...
            "m", 300, "field", "real", "snrDb", 20, ...
            "seed", seed);
    case "roth_fourier"
        cfg = struct( ...
            "ensemble", "partial_fourier", ...
            "N", 20, "n", 50, "s", 3, "sigma", 10, ...
            "m", 200, "field", "complex", "snrDb", Inf, ...
            "seed", seed);
    case "roth_kronecker"
        cfg = struct( ...
            "ensemble", "kronecker", ...
            "N", 20, "n", 50, "s", 3, "sigma", 10, ...
            "outerMeasurements", 12, "innerMeasurements", 30, ...
            "field", "real", "snrDb", Inf, ...
            "seed", seed);
    case "smoke_test"
        cfg = struct( ...
            "ensemble", "gaussian", ...
            "N", 4, "n", 6, "s", 2, "sigma", 2, ...
            "m", 12, "field", "real", "snrDb", Inf, ...
            "seed", seed);
    otherwise
        error("channelgen:profile:UnknownProfile", ...
            "Unknown CS profile '%s'.", name);
end
end
